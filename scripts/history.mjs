// Generates docs/HISTORY.md, a chronological index of the archived OpenSpec changes.
// Usage: node scripts/history.mjs          (writes docs/HISTORY.md; running it again produces no diff)
//        node scripts/history.mjs --check  (exit code 1 when docs/HISTORY.md is out of date)
//
// Every directory `openspec/changes/archive/<YYYY-MM-DD>-<name>/` becomes one row: the date, the change name
// (linked to its proposal) and the first sentence of the "## Why" section of the proposal.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const archive = join(root, 'openspec', 'changes', 'archive');
const output = join(root, 'docs', 'HISTORY.md');

/**
 * The first sentence of a text: ends at `.`, `!` or `?` followed by a space and the start of a new sentence,
 * not after an abbreviation such as `e.g.` or `i.e.`.
 *
 * @param {string} text whitespace-collapsed text
 * @returns {string}
 * @example firstSentence('Users need X (e.g. Y). Then Z.') // 'Users need X (e.g. Y).'
 */
export function firstSentence(text) {
    const pattern = /[.!?](?=\s+[A-Z`"'(*[]|$)/g;
    let match;
    while ((match = pattern.exec(text)) !== null) {
        const head = text.slice(0, match.index + 1);
        if (/\b(e\.g|i\.e|vs|etc|cf)\.$/i.test(head)) continue;
        return head;
    }
    return text;
}

/**
 * The first sentence of the `## Why` section of a proposal, or a placeholder when there is none.
 *
 * @param {string} proposal the proposal source
 * @returns {string}
 */
export function why(proposal) {
    const match = /^##\s+Why\s*\n([\s\S]*?)(?=^##\s|(?![\s\S]))/m.exec(proposal);
    if (!match) return '(no reason recorded)';
    // Links in a proposal are relative to its own directory; keep only their text.
    const text = match[1].replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/\s+/g, ' ').trim();
    return text ? firstSentence(text) : '(no reason recorded)';
}

/** Escapes what would break a Markdown table cell. */
const cell = (text) => text.replace(/\|/g, '\\|');

/** Builds the Markdown of the index from the archive directory. */
export function build() {
    const entries = readdirSync(archive, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && /^\d{4}-\d{2}-\d{2}-/.test(entry.name))
        .map((entry) => entry.name)
        .sort();

    const rows = entries.map((dir) => {
        const date = dir.slice(0, 10);
        const name = dir.slice(11);
        const file = join(archive, dir, 'proposal.md');
        const reason = existsSync(file) ? why(readFileSync(file, 'utf8')) : '(no proposal in the archive)';
        return `| ${date} | [${name}](../openspec/changes/archive/${dir}/proposal.md) | ${cell(reason)} |`;
    });

    return `# Development history

The package was developed change by change with [OpenSpec](https://github.com/Fission-AI/OpenSpec). Each change was proposed, specified, designed, implemented and then archived. This page lists every archived change in date order (changes of the same day in name order), with the first sentence of its reason. It is generated by \`node scripts/history.mjs\` from \`openspec/changes/archive/\`: do not edit it by hand.

## How to read OpenSpec

- \`openspec/specs/<capability>/spec.md\` is the **current** specification of a capability: requirements ("The system SHALL …") each with scenarios (WHEN … THEN …). \`openspec list --specs\` lists them.
- \`openspec/changes/archive/<date>-<name>/\` is one finished change:
  - \`proposal.md\` — **why** the change was made, **what changes** and its impact (start here);
  - \`design.md\` — the decisions, the alternatives that were rejected and the risks;
  - \`specs/<capability>/spec.md\` — the delta: requirements added, modified or removed by the change, merged into the main specification when the change was archived;
  - \`tasks.md\` — the implementation checklist.
- To learn why something is the way it is, find the capability in \`openspec/specs/\`, then search the archive for the changes that touched it (\`grep -rl "<capability>" openspec/changes/archive\`).
- The topic pages in [docs/](README.md) describe how the code works today; this history explains how it came to be. Some archived changes were made before the code became a package and mention the application's own paths and commands (\`App\\…\`, \`docker compose exec app\`, browser tests); they are kept as written, and the early ones are written in Ukrainian.

## Archived changes (${rows.length})

| Date | Change | Why |
|------|--------|-----|
${rows.join('\n')}
`;
}

const content = build();
if (process.argv.includes('--check')) {
    const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
    if (current !== content) {
        console.error('docs/HISTORY.md is out of date: run `node scripts/history.mjs`.');
        process.exit(1);
    }
    console.log('docs/HISTORY.md is up to date.');
} else {
    writeFileSync(output, content);
    console.log(`docs/HISTORY.md: ${content.split('\n').filter((l) => l.startsWith('| 20')).length} changes.`);
}
